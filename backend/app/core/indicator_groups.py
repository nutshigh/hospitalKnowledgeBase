def _norm(name: str) -> str:
    return re.sub(r"[\s\u3000]+", "", name)


# 可作落库/分组栏目的合法取值 = 能折叠的模块(有分类规则的子集),按 Excel 顺序
PANEL_HINTS: Tuple[str, ...] = tuple(m for m in MODULE_ORDER if m in _RULES)


_PANEL_LOOKUP: Dict[str, str] = {_norm(m): m for m in PANEL_HINTS}


def normalize_panel(raw: Optional[str]) -> Optional[str]:
    """清洗模型输出的栏目:去空白后按归一化键回查 PANEL_HINTS,返回规范名(保留原始空白);未命中返回 None。"""
    if not raw:
        return None
    return _PANEL_LOOKUP.get(_norm(str(raw)))


def classify(item_name: str) -> Optional[str]:
    if not item_name:
        return None
    name = _norm(item_name)
    for module in MODULE_ORDER:
        rule = _RULES.get(module)
        if rule is None:
            continue
        includes, excludes = rule
        if not any(tok in name for tok in includes):
            continue
        if any(tok in name for tok in excludes):
            continue
        return module
    return None


def group_indicators(rows: List[dict]) -> Tuple[List[dict], List[str]]:
    present: List[str] = []
    for row in rows:
        stored = normalize_panel(row.get("category") or "")
        g = stored if stored else classify(str(row.get("item_name") or ""))
        row["group"] = g
        if g and g not in present:
            present.append(g)
    order = {m: i for i, m in enumerate(MODULE_ORDER)}
    present.sort(key=lambda m: order.get(m, len(MODULE_ORDER)))
    return rows, present
