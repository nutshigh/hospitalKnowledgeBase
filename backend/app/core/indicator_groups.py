def _norm(name: str) -> str:
    return re.sub(r"[\s\u3000]+", "", name)


# === 2026-09-28: 血/尿同名项消歧(毕惠丽报告用户反馈) ===
# 裸名"红细胞/白细胞"血、尿检同名(报告里都是"红细胞"), 仅按名称分不开:
# ① 单位优先: 血检单位 10^12/10^9/L, 尿检单位 /μl //HP /ul 个/HP 等;
# ② 报告级尿检上下文: 出现"白细胞酯酶/亚硝酸盐/尿比重/尿蛋白…"等**仅尿检**项时报
#    告有尿检 → 无单位裸名归尿常规; 同时有粪检项时不套用(隐血等粪检同名歧义)。
_BARE_SAME_NAME = ("红细胞", "白细胞")
_BARE_URINE_ONLY = ("红细胞", "白细胞", "隐血")
# 2026-10-19: 白带常规上下文与共享裸名(陈婷婷 白带白细胞/HP 与血常规白细胞重名)
_VAGINAL_CTX = ("清洁度", "滴虫", "霉菌", "加特纳", "线索细胞", "阴道", "白带")
_SHARED_BODY_NAMES = ("白细胞", "红细胞", "上皮细胞", "杆菌", "杂菌", "球菌", "真菌",
                      "滴虫", "脓细胞")
# 2026-10-19: 去掉裸 /l —— "/L"(per liter) 是血/生化单位, 曾把 10^12/L、g/L 判成尿;
# 真正尿/体液单位 = /μL、/uL、/ul、/HP、/LP、/hpf、/lpf、/h
# 2026-10-19: 兼容 OCR 丢失斜杠的裸 ul/uL/μL(陈行富"白细胞 3.3 ul")
_URINE_UNIT_RE = re.compile(
    r"/\s*(?:[uμµ]\s*l|hpf|h|lpf|lp|h\b)|^(?:[uμµ]\s*l)$", re.I)
# 2026-10-19(用户反馈): 原 1[29] 只认 10^12, 10^9/L(白细胞/血小板)被当尿单位 →
# 血常规项整批误分尿常规。支持 10^9/10^12 及 X/×/~ 前缀。
_BLOOD_UNIT_RE = re.compile(r"(?:[xX×*]\s*)?10\s*[\^~*]?\s*(?:9|12)\b")
_URINE_CTX = ("白细胞酯酶", "亚硝酸盐", "电导率", "尿比重", "尿蛋白", "尿胆原", "尿葡萄糖",
              "尿酮体", "尿隐血", "尿白细胞", "尿红细胞", "尿沉渣", "尿液", "微白蛋白", "尿肌酐")
_STOOL_CTX = ("粪便", "大便", "便潜血", "粪常规", "脂肪球", "虫卵", "未消化食物")


def _unit_is_blood(unit: object) -> bool:
    return bool(unit) and bool(_BLOOD_UNIT_RE.search(_norm(str(unit))))


def _unit_is_urine(unit: object) -> bool:
    return bool(unit) and bool(_URINE_UNIT_RE.search(_norm(str(unit))))


# 可作落库/分组栏目的合法取值 = 能折叠的模块(有分类规则的子集),按 Excel 顺序
PANEL_HINTS: Tuple[str, ...] = tuple(m for m in MODULE_ORDER if m in _RULES)


_PANEL_LOOKUP: Dict[str, str] = {_norm(m): m for m in PANEL_HINTS}


def normalize_panel(raw: Optional[str]) -> Optional[str]:
    """清洗模型输出的栏目:去空白后按归一化键回查 PANEL_HINTS,返回规范名(保留原始空白);未命中返回 None。"""
    if not raw:
        return None
    return _PANEL_LOOKUP.get(_norm(str(raw)))


# 2026-10-13: 西里尔字母视觉同形字归一(恩施"脂蛋白а LP(а)" —— а/е/о/р/с/х/у 是
# 西里尔字符, 血脂关键词"脂蛋白a"匹配不上, 分类落空)。
_CYR2LAT = str.maketrans({"а": "a", "А": "A", "е": "e", "Е": "E", "о": "o", "О": "O",
                          "р": "p", "Р": "P", "с": "c", "С": "C", "х": "x", "Х": "X",
                          "у": "y", "У": "Y"})


def classify(item_name: str, unit: Optional[str] = None) -> Optional[str]:
    if not item_name:
        return None
    name = _norm(item_name.translate(_CYR2LAT))
    # 2026-09-28: "红细胞/白细胞"裸名按单位消歧(毕惠丽"红细胞"51.34 /μl 曾误入血常规)
    # 2026-10-19(用户反馈): 扩展 —— 血常规**全名**("红细胞数"/"白细胞计数")带尿单位
    # (/μL、/HP…)也是尿检项(包强/陈佳漩 血尿同名误分); 血单位(10^9/10^12)恒判血常规。
    # 2026-10-19(用户反馈): 隐血/潜血=尿检语义(血常规无此词), 先于"红细胞"命中;
    # 裸"蛋白"=尿蛋白(陈婷婷/封猛 尿常规)
    if ("隐血" in name or "潜血" in name) and not any(
            t in name for t in ("粪", "大便", "便")):
        return "尿常规"
    if name == "蛋白":
        return "尿常规"
    # 2026-10-19(陈阳/陈行富反馈): 裸"PH"/"尿PH"(尿常规表)归尿常规
    if name.strip().upper() in ("PH", "尿PH"):
        return "尿常规"
    if unit:
        if _unit_is_blood(unit):
            return "血常规"
        if _unit_is_urine(unit) and (
                name in _BARE_SAME_NAME
                or any(tok in name for tok in _RULES["血常规"][0])):
            return "尿常规"
    for module in MODULE_ORDER:
        rule = _RULES.get(module)
        if rule is None:
            continue
        includes, excludes = rule
        if not any(tok in name for tok in includes):
            continue
        if any(tok in name for tok in excludes):
            continue
        return module
    return None


def group_indicators(rows: List[dict]) -> Tuple[List[dict], List[str]]:
    # 2026-09-28: 报告级尿检上下文(见上) —— 有尿检项且无粪检项时, 无单位裸名归尿常规
    _names = [_norm(str(r.get("item_name") or "")) for r in rows]
    _has_urine = any(any(t in n for t in _URINE_CTX) for n in _names)
    _has_stool = any(any(t in n for t in _STOOL_CTX) for n in _names)
    _has_vaginal = any(any(t in n for t in _VAGINAL_CTX) for n in _names)
    present: List[str] = []
    for row, nm in zip(rows, _names):
        stored = normalize_panel(row.get("category") or "")
        g = stored if stored else classify(str(row.get("item_name") or ""), row.get("unit"))
        # 2026-10-19(韩先锋): 同名"葡萄糖"区分 —— 结果非数值(尿糖 "-"/"阴性")归尿常规,
        # 数值(mmol/L)保持血糖
        _rv_glu = str(row.get("result_value") or "").strip()
        if (not stored and nm == "葡萄糖" and _rv_glu
                and not re.search(r"\d", _rv_glu)):
            g = "尿常规"
        if (not stored and nm in _BARE_URINE_ONLY and g in (None, "血常规", "大便常规")
                and not _unit_is_blood(row.get("unit"))
                and _has_urine and not _has_stool):
            g = "尿常规"
